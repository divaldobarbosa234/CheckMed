    static func string(_ key: Key, locale: AppLocale, args: [CVarArg] = []) -> String {
        let format = table[locale]?[key] ?? table[.english]?[key] ?? key.rawValue
        if args.isEmpty { return format }
        return String(format: format, locale: locale.foundationLocale, arguments: args)
    }

