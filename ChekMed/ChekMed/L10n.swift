import Foundation

enum AppLocale: String, CaseIterable, Identifiable {
    case english = "en"
    case portuguese = "pt"
    case spanish = "es"
    case french = "fr"

    var id: String { rawValue }

    /// Brazilian Portuguese (`pt-BR`) unless a later pass needs `pt-PT`.
    var identifier: String {
        switch self {
        case .english: "en"
        case .portuguese: "pt-BR"
        case .spanish: "es"
        case .french: "fr"
        }
    }

    var foundationLocale: Locale { Locale(identifier: identifier) }

    var displayName: String {
        switch self {
        case .english: "English"
        case .portuguese: "Português"
        case .spanish: "Español"
        case .french: "Français"
        }
    }

    static func fromStored(_ value: String) -> AppLocale {
        let trimmed = value.trimmingCharacters(in: .whitespacesAndNewlines)
        if let match = AppLocale(rawValue: trimmed) { return match }
        switch trimmed.lowercased() {
        case "english", "en-us", "en-gb": return .english
        case "portuguese", "português", "pt-br", "pt-pt", "pt_br": return .portuguese
        case "spanish", "español", "es-es", "es-mx": return .spanish
        case "french", "français", "francais", "fr-fr": return .french
        default: return .english
        }
    }
}

